"""Write the pre-committed tuning trials of E0 (decision D11 part 2). Owner: Nouran.

Every model gets the same budget: 12 trial settings, drawn here by random search with a seed derived from
the model name, written to configs/tuning/<model>.yaml and committed BEFORE any E0 run. Every fold tries the
same 12 and keeps the best on its own validation block (8-class macro-F1). Re-running this script must
reproduce the committed files byte for byte (tests/test_tuning_configs.py checks it).

Run: python -m experiments.make_tuning_configs            (writes configs/tuning/)
     python -m experiments.make_tuning_configs --check    (exit 1 if the committed files differ)
"""
import argparse
import sys
import zlib
from itertools import product
from pathlib import Path

import numpy as np

N_TRIALS = 12
OUT = Path("configs/tuning")
LADDER = (64, 120, 128, 256, 512, 1_000, 3_000)          # D11 part 2: 64 = vqc, 120 = vqc_lin / vqc_noent
TORCH_FIXED = {"batch_size": 256, "max_epochs": 100, "patience": 10}

# name: (family, fixed settings, search space). Space entries: ("log", lo, hi) | ("uniform", lo, hi) | ("choice", [...])
QUANTUM = {"lr": ("log", 1e-3, 1e-1)}
SMALL_NN = {"lr": ("log", 1e-4, 3e-2), "weight_decay": ("choice", [0.0, 1e-5, 1e-4])}
MODELS = {
    "vqc": ("quantum", {**TORCH_FIXED, "n_layers": 3, "entangler": "chain", "readout": "local"}, QUANTUM),
    "vqc_lin": ("quantum", {**TORCH_FIXED, "n_layers": 3, "entangler": "chain", "readout": "linear"}, QUANTUM),
    "vqc_noent": ("quantum", {**TORCH_FIXED, "n_layers": 3, "entangler": "none", "readout": "linear"}, QUANTUM),
    **{f"mlp_p{p}": ("mlp", {**TORCH_FIXED, "target_params": p}, SMALL_NN) for p in LADDER},
    "rff": ("rff", {**TORCH_FIXED, "max_frequency": 3}, SMALL_NN),
    "mlp_large": ("mlp", {**TORCH_FIXED, "hidden": [256, 256]},
                  {**SMALL_NN, "dropout": ("choice", [0.0, 0.1])}),
    "lr": ("sklearn", {"max_iter": 1000}, {"C": ("log", 1e-4, 1e2)}),
    "xgb": ("xgboost", {"n_estimators": 1000, "early_stopping_rounds": 50, "tree_method": "hist"},
            {"max_depth": ("choice", [4, 6, 8, 10]), "learning_rate": ("log", 0.03, 0.3),
             "subsample": ("uniform", 0.6, 1.0), "colsample_bytree": ("uniform", 0.6, 1.0),
             "min_child_weight": ("log", 1.0, 10.0)}),
    "rf": ("sklearn", {"n_estimators": 300},
           {"max_depth": ("choice", [None, 16, 32]), "max_features": ("choice", ["sqrt", 0.3, 0.5]),
            "min_samples_leaf": ("choice", [1, 5, 20])}),
}


def seed_for(name: str) -> int:
    return zlib.crc32(f"E0-D11-{name}".encode())


def _round(v):
    return float(f"{v:.4g}")


def draw(space: dict, seed: int, n: int = N_TRIALS) -> list[dict]:
    rng = np.random.default_rng(seed)
    if all(spec[0] == "choice" for spec in space.values()):          # small grid: draw without repeats
        grid = list(product(*[spec[1] for spec in space.values()]))
        pick = rng.choice(len(grid), size=min(n, len(grid)), replace=False)
        return [dict(zip(space, grid[i])) for i in pick]
    trials = []
    for _ in range(n):
        t = {}
        for k, spec in space.items():
            if spec[0] == "log":
                t[k] = _round(float(np.exp(rng.uniform(np.log(spec[1]), np.log(spec[2])))))
            elif spec[0] == "uniform":
                t[k] = _round(float(rng.uniform(spec[1], spec[2])))
            else:
                v = spec[1][int(rng.integers(len(spec[1])))]
                t[k] = v
        trials.append(t)
    return trials


def _yaml_value(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return v
    if isinstance(v, list):
        return "[" + ", ".join(_yaml_value(x) for x in v) + "]"
    if isinstance(v, float):
        return repr(v)
    return str(v)


def _yaml_map(d):
    return "{" + ", ".join(f"{k}: {_yaml_value(v)}" for k, v in d.items()) + "}"


def render(name: str) -> str:
    family, fixed, space = MODELS[name]
    seed = seed_for(name)
    lines = [
        "# Generated by experiments/make_tuning_configs.py (decision D11 part 2). Do not edit by hand.",
        f"model: {name}",
        f"family: {family}",
        f"seed: {seed}",
        f"n_trials: {N_TRIALS}",
        "select: validation macro_f1 (8-class), per fold",
        f"fixed: {_yaml_map(fixed)}",
        "space:",
        *[f"  {k}: [{', '.join(_yaml_value(x) for x in spec[1])}]" if spec[0] == "choice"
          else f"  {k}: {spec[0]}({_yaml_value(spec[1])}, {_yaml_value(spec[2])})" for k, spec in space.items()],
        "trials:",
        *[f"  - {_yaml_map({'id': i, **t})}" for i, t in enumerate(draw(space, seed))],
    ]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="compare with the committed files, write nothing")
    a = ap.parse_args()
    bad = []
    for name in MODELS:
        path, text = OUT / f"{name}.yaml", render(name)
        if a.check:
            if not path.exists() or path.read_text() != text:
                bad.append(str(path))
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if a.check:
        print("tuning configs match" if not bad else f"differ: {bad}")
        sys.exit(1 if bad else 0)
    print(f"wrote {len(MODELS)} files to {OUT}/")


if __name__ == "__main__":
    main()
